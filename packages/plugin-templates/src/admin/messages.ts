/** Keys of {@link templatesMessages}. */
export type TemplatesMessageKey = MessageKey<typeof templatesMessages>;

/** Translate function of the templates namespace. */
export type TemplatesT = Translator<TemplatesMessageKey>["t"];

const has = (key: string): key is TemplatesMessageKey =>
  Object.hasOwn(templatesMessages.locales.en, key);

/** A catalog variable's label: brand variables from the catalog, others as configured. */
export function variableLabel(i18n: AdminI18n, variable: Pick<CatalogVariable, "path" | "label">) {
  const key = `variable.${variable.path}`;
  return has(key) ? i18n.scope(templatesMessages).t(key) : i18n.text(variable.label);
}

/** A variable group's name: the built-in groups translated, others as configured. */
export function groupLabel(i18n: AdminI18n, group: string): string {
  const { t } = i18n.scope(templatesMessages);
  if (group === BRAND_GROUP) return t("group.brand");
  return group === DEFAULT_GROUP ? t("group.data") : group;
}
