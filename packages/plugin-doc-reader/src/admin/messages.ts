export type DocReaderKey = MessageKey<typeof docReaderMessages>;

/** The translator of the doc reader's messages. */
export type DocReaderT = Translator<DocReaderKey>["t"];

/** The doc reader's translator for a page's `i18n`. */
export function docReaderT(i18n: AdminI18n): DocReaderT {
  return i18n.scope(docReaderMessages).t;
}

function known(
  t: DocReaderT,
  prefix: "state" | "status",
  values: readonly string[],
  value: string,
): string {
  return values.includes(value) ? t(`${prefix}.${value}` as DocReaderKey) : value;
}

const STATES = ["queued", "running", "done", "failed", "cancelled", "draft", "published"];
const STATUSES = ["OK", "INCOMPLETE", "NO_MATCH", "NO_TEXT", "ERROR", "SKIPPED"];

/** A job, run or version state for display. Unknown states show as stored. */
export function stateLabel(t: DocReaderT, state: string): string {
  return known(t, "state", STATES, state);
}

/** An extraction status for display. Unknown statuses show as stored. */
export function statusLabel(t: DocReaderT, status: string): string {
  return known(t, "status", STATUSES, status);
}
