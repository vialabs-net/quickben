import { familyOf, tableSpecs } from "./columns";
import { createSchemaDdl, createTableDdl, indexDdl } from "./ddl";
import { resolveTarget, schemaOf, writeOut } from "./generate";
import { prismaSource } from "./prisma";

import type { Dialect } from "./columns";
import type { DatabaseSchema, QuickbenConfig } from "@quickben/core";

/** Options of {@link generateSql}. */
export interface GenerateSqlOptions {
  /** Defaults to the dialect of `config.db` when it is a Drizzle adapter. */
  dialect?: Dialect;
  /** Postgres schema of the tables. Defaults to the `schema` of `config.db`. */
  schema?: string;
  /** `sql` (default): DDL statements. `prisma`: Prisma models for the same tables. */
  format?: "sql" | "prisma";
  /** Write the output to this path. Directories are created. */
  out?: string;
}

/** Statements as a SQL script: each ends with `;`, a blank line between them. */
export function sqlScript(statements: readonly string[]): string {
  return statements.map((statement) => `${statement};\n`).join("\n");
}

/** DDL statements that create every table and index of `schema`, in order. */
export function sqlStatements(
  schema: DatabaseSchema,
  dialect: Dialect,
  pgSchema?: string,
): string[] {
  const family = familyOf(dialect);
  const options = { schema: family === "pg" ? pgSchema : undefined };
  return [
    ...(options.schema === undefined ? [] : [createSchemaDdl(options.schema)]),
    ...tableSpecs(schema).flatMap((table) => [
      createTableDdl(table, family, options),
      ...indexDdl(table, family, options),
    ]),
  ];
}

/** SQL script that creates the tables of `schema`, for any migration tool. */
export function sqlSource(schema: DatabaseSchema, dialect: Dialect, pgSchema?: string): string {
  return [
    `-- Generated by @quickben/db-drizzle from the Quickben config (${dialect}).`,
    "-- Run `quickben-drizzle sql` again after you change collections.",
    "",
    sqlScript(sqlStatements(schema, dialect, pgSchema)),
  ].join("\n");
}

/**
 * Plain SQL DDL (or Prisma models with `format: "prisma"`) for every collection of a config:
 * the tables, columns and indexes the adapter expects. Paste it into the migrations of the tool
 * that owns the database, and run the adapter with `push: false`.
 */
export async function generateSql(
  config: QuickbenConfig,
  options: GenerateSqlOptions = {},
): Promise<string> {
  const { dialect, schema } = resolveTarget("generateSql", config, options);
  const source =
    options.format === "prisma"
      ? prismaSource(schemaOf(config), dialect, schema)
      : sqlSource(schemaOf(config), dialect, schema);
  if (options.out) await writeOut(options.out, source);
  return source;
}
