import type { FieldType } from "./fields";

/** A stored document as adapters see it: plain JSON-compatible values keyed by field name. */
export type DocumentData = Record<string, unknown>;

/** Comparison operators of the portable query model. */
export type WhereOperator =
  "eq" | "ne" | "in" | "notIn" | "lt" | "lte" | "gt" | "gte" | "contains" | "startsWith" | "exists";

/**
 * Normalized filter passed to adapters. Core validates and normalizes every `where`
 * before an adapter sees it.
 *
 * - `{ and: [] }` matches every document. `{ or: [] }` matches none.
 * - Comparisons never match `null`, except `ne`, `notIn` and `exists: false`.
 * - `contains` and `startsWith` ignore case.
 * - On array fields (`many: true`): `contains` = has the value, `in` = has any value,
 *   `notIn` = has none of the values, `exists` = is not empty.
 */
export type WhereNode =
  { and: WhereNode[] } | { or: WhereNode[] } | { field: string; op: WhereOperator; value: unknown };

/** One sort key. Nulls sort last in `asc` and first in `desc`. */
export interface SortSpec {
  field: string;
  direction: "asc" | "desc";
}

/** Field description passed to {@link DatabaseAdapter.init}. */
export interface FieldSchema {
  name: string;
  type: FieldType;
  many: boolean;
  required: boolean;
  unique: boolean;
  index: boolean;
  /** Related collection slug, for `relation` fields. */
  to?: string;
  /** Allowed values, for `select` fields. */
  options?: readonly string[];
  /** Whole numbers only, for `number` fields. */
  integer?: boolean;
}

/**
 * Collection description passed to {@link DatabaseAdapter.init}. Every collection also has
 * the system fields `id` (string primary key), `createdAt` and `updatedAt` (ISO strings).
 */
export interface CollectionSchema {
  slug: string;
  fields: readonly FieldSchema[];
}

/** Everything an adapter needs to prepare storage. */
export interface DatabaseSchema {
  collections: readonly CollectionSchema[];
}

/** Arguments of {@link DatabaseAdapter.find}. */
export interface FindArgs {
  collection: string;
  where?: WhereNode;
  /** Already includes a final `id` key, so the order is total. */
  sort?: readonly SortSpec[];
  limit?: number;
  offset?: number;
  /** Fields to return. `id` is always returned. Omitted = all fields. */
  select?: readonly string[];
}

/**
 * The storage contract. Core calls it with validated data and normalized queries.
 *
 * Rules every adapter follows (checked by `@quickben/adapter-tests`):
 * - Ids are strings generated by core. Never generate ids.
 * - Return documents as plain objects with the same values core wrote. Dates are ISO strings.
 *   A field missing in storage may be returned as missing or `null`.
 * - Throw `ConflictError` from `@quickben/core` when a `unique` field or the id is taken.
 *   `null` values never conflict.
 * - No joins. Relations are ids; core loads related documents.
 * - `transaction(fn)` runs `fn` with an adapter bound to the transaction. When `fn` throws,
 *   nothing it wrote is kept. Calling `transaction` on that adapter joins the same transaction.
 */
export interface DatabaseAdapter<TRaw = unknown> {
  /** Adapter name for messages, e.g. `memory`. */
  readonly name: string;
  /** Native client for custom queries (for example a Drizzle database). */
  readonly raw: TRaw;
  /** Prepare storage. Called once by `createQuickben` before any other method. */
  init(schema: DatabaseSchema): Promise<void>;
  find(args: FindArgs): Promise<DocumentData[]>;
  findOne(args: Omit<FindArgs, "limit" | "offset">): Promise<DocumentData | null>;
  count(args: { collection: string; where?: WhereNode }): Promise<number>;
  /** Insert `data` (it includes `id`, `createdAt` and `updatedAt`). Returns the stored document. */
  create(args: { collection: string; data: DocumentData }): Promise<DocumentData>;
  /** Merge `data` into the document. Returns the stored document, or `null` if it does not exist. */
  update(args: {
    collection: string;
    id: string;
    data: DocumentData;
  }): Promise<DocumentData | null>;
  /** Returns `false` when the document does not exist. */
  delete(args: { collection: string; id: string }): Promise<boolean>;
  transaction<T>(fn: (tx: DatabaseAdapter<TRaw>) => Promise<T>): Promise<T>;
  /** Release connections. Optional. */
  close?(): Promise<void>;
}
